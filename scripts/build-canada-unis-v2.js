/**
 * Curated program data for 66 new Canada institutions (v2).
 * Run: node scripts/build-canada-unis-v2.js
 * Output: data/scraped/canada/<id>.json
 * Valid levels: Graduate Certificate, Advanced Diploma, Honours Bachelor, Masters, PhD
 */

const fs = require('fs');
const path = require('path');
const OUT_DIR = path.join(__dirname, '../data/scraped/canada');

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 80);
}

function make(id, website, campus, ielts, intakes, feesByLevel, programs) {
  return programs.map(p => {
    const [name, level, durationYears, feeOverride] = p;
    const feeKey = level === 'PhD' ? 'phd'
      : /Masters|Master|MBA/i.test(level) ? 'masters'
      : /Graduate Certificate/i.test(level) ? 'gradCert'
      : /Advanced Diploma/i.test(level) ? 'advDip'
      : /Honours Bachelor|Bachelor/i.test(level) ? 'bachelor'
      : 'default';
    const annualCAD = feeOverride || feesByLevel[feeKey] || feesByLevel.default;
    const dur = durationYears < 1 ? `${Math.round(durationYears * 12)} months`
      : `${durationYears} year${durationYears !== 1 ? 's' : ''}`;
    return {
      name, level,
      slug: `${id}-${slugify(name)}`,
      url: website,
      duration: dur, durationYears,
      annualCAD,
      totalCAD: Math.round(annualCAD * durationYears),
      ieltsMin: ielts,
      intakeMonths: intakes,
      campus,
    };
  });
}

function build(id, name, website, campus, ielts, intakes, feesByLevel, programs) {
  const data = make(id, website, campus, ielts, intakes, feesByLevel, programs);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUT_DIR, `${id}.json`), JSON.stringify(data, null, 2), 'utf8');
  const byLevel = {};
  data.forEach(c => { byLevel[c.level] = (byLevel[c.level] || 0) + 1; });
  console.log(`✅ ${name}: ${data.length} courses`);
  console.log('   By level:', byLevel);
}

