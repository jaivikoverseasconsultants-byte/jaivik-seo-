function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9\s-]/g, '').replace(/\s+/g, '-').replace(/-+/g, '-').substring(0, 80);
}

function getLevel(name) {
  if (/\bMBA\b/.test(name)) return { level: 'MBA', studyLevel: 'Postgraduate' };
  if (/\b(MSc|MA |MRes|LLM|MPhil|MEng|MFA|MPH|MPA|MSt|MArch|MProf)\b/.test(name)) return { level: 'Masters', studyLevel: 'Postgraduate' };
  if (/\bMaster\b/.test(name)) return { level: 'Masters', studyLevel: 'Postgraduate' };
  if (/\b(BSc|BEng|BA |LLB|BFA|BArch|BEd|BComm|BBus|BCom)\b/.test(name)) return { level: 'Bachelors', studyLevel: 'Undergraduate' };
  if (/\bBachelor\b/.test(name)) return { level: 'Bachelors', studyLevel: 'Undergraduate' };
  if (/\bPhD\b/.test(name)) return { level: 'PhD', studyLevel: 'Postgraduate' };
  return { level: 'Masters', studyLevel: 'Postgraduate' };
}

