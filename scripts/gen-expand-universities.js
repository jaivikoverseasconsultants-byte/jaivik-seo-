function makeCourse(u, name, idx) {
  const { level, studyLevel } = getLevel(name);
  const isUG = studyLevel === 'Undergraduate';
  const isMBA = level === 'MBA';

  const annualBase = isUG ? u.feeAnnualUG : isMBA ? u.feeAnnualPG * 1.4 : u.feeAnnualPG;
  const multiplier = name.includes('Finance') || name.includes('FinTech') ? 1.1
    : name.includes('MBA') ? 1.4
    : name.includes('Data Science') || name.includes('AI') ? 1.05
    : 1;
  const annual = Math.round(annualBase * multiplier);

  const intakes = isUG ? u.intakesUG : u.intakesPG;
  const slug = `${u.prefix}-${slugify(name)}`;

  const base = {
    id: `${u.prefix}-${idx + 1}`,
    name,
    slug,
    url: u.url,
    level,
    studyLevel,
    duration: isUG ? '3 years' : isMBA ? '1.5 years' : '1 year',
    durationYears: isUG ? 3 : isMBA ? 2 : 1,
    annualINR: Math.round(annual * u.rate.inr),
    ieltsMin: isUG ? u.ielts - 0.5 : isMBA ? u.ielts + 0.5 : u.ielts,
    toeflMin: u.toefl,
    pteMin: u.pte,
    intakeMonths: intakes,
    campus: u.campus,
    country: u.country,
    state: u.state,
    city: u.city,
    countryCode: u.cc,
  };

  if (u.currency === 'EUR') {
    return {
      ...base,
      annualEUR: annual,
      annualUSD: Math.round(annual * u.rate.usd),
      totalEUR: annual * base.durationYears,
      livingCostEUR: u.livingEUR,
      livingCostUSD: u.living.usd,
      livingCostINR: u.living.inr,
    };
  } else if (u.currency === 'SGD') {
    return {
      ...base,
      annualSGD: annual,
      annualUSD: Math.round(annual * u.rate.usd),
      totalSGD: annual * base.durationYears,
      livingCostSGD: u.livingSGD,
      livingCostUSD: u.living.usd,
      livingCostINR: u.living.inr,
    };
  } else if (u.currency === 'AED') {
    return {
      ...base,
      annualAED: annual,
      annualUSD: Math.round(annual * u.rate.usd),
      totalAED: annual * base.durationYears,
      livingCostAED: u.livingAED,
      livingCostUSD: u.living.usd,
      livingCostINR: u.living.inr,
    };
  } else {
    return {
      ...base,
      annualUSD: annual,
      totalUSD: annual * base.durationYears,
      livingCostUSD: u.livingUSD,
      livingCostINR: u.living.inr,
    };
  }
}

function buildFile(u, courses) {
  let iface;
  if (u.currency === 'EUR') {
    iface = `  annualEUR: number; annualUSD: number; annualINR: number; totalEUR: number;
  livingCostEUR: number; livingCostUSD: number; livingCostINR: number;`;
  } else if (u.currency === 'SGD') {
    iface = `  annualSGD: number; annualUSD: number; annualINR: number; totalSGD: number;
  livingCostSGD: number; livingCostUSD: number; livingCostINR: number;`;
  } else if (u.currency === 'AED') {
    iface = `  annualAED: number; annualUSD: number; annualINR: number; totalAED: number;
  livingCostAED: number; livingCostUSD: number; livingCostINR: number;`;
  } else {
    iface = `  annualUSD: number; annualINR: number; totalUSD: number;
  livingCostUSD: number; livingCostINR: number;`;
  }

  return `// Real course data for ${u.name}
// Generated: ${new Date().toISOString().split('T')[0]}

export interface ${u.ifaceName} {
  id: string; name: string; slug: string; url: string;
  level: string; studyLevel: string; duration: string; durationYears: number;
${iface}
  ieltsMin: number; toeflMin: number; pteMin: number;
  intakeMonths: string[]; campus: string;
  country: string; state: string; city: string; countryCode: string;
}

export const ${u.varName}: ${u.ifaceName}[] = ${JSON.stringify(courses, null, 2)};

export function ${u.getFn}(slug: string): ${u.ifaceName} | undefined {
  return ${u.varName}.find(c => c.slug === slug);
}
`;
}

let totalCourses = 0;
let filesUpdated = 0;

for (const u of UNIVERSITIES) {
  const programs = [...new Set(u.programs)]; // deduplicate
  const courses = programs.map((name, idx) => makeCourse(u, name, idx));
  const content = buildFile(u, courses);
  fs.writeFileSync(u.file, content);
  console.log(`✅ ${u.name}: ${courses.length} courses → ${u.file}`);
  totalCourses += courses.length;
  filesUpdated++;
}

console.log(`\n✅ Generated ${totalCourses} courses for ${filesUpdated} universities`);
