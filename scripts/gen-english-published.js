// Generates data/english-published.ts — which English tests each university actually PUBLISHES.
//
// Why: course rows always carry ieltsMin/toeflMin/pteMin, but for many universities some of those
// are house defaults, not the provider's own figure. Pages were printing all three as requirements
// ("PTE Academic 58+ also accepted") for universities that publish no PTE score at all.
//
// Source of truth for Canada: data/wave-canada/institution-english.json, written by
// scripts/ca-find-english.js from each university's own English-requirements page. An empty array
// for a test means the page did not state a score for it; resolved:false / doNotPublish means the
// page we reached was tiered or a pathway page, so NONE of its bands can be presented as the
// requirement (Queen's, York, KPU).
//
// Usage: node scripts/gen-english-published.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const INST = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/wave-canada/institution-english.json'), 'utf8'));

// institution-english.json key -> university slug in data/universities.ts
const SLUGS = {
  'Algonquin College': 'algonquin-college',
  'Durham College': 'durham-college',
  'Kwantlen (KPU)': 'kwantlen-polytechnic-university',
  'Red River College': 'red-river-college-polytechnic',
  'University of Alberta': 'university-of-alberta',
  'University of Waterloo': 'university-of-waterloo',
  "Queen's University": 'queens-university',
  'University of Ottawa': 'university-of-ottawa',
  'Dalhousie University': 'dalhousie-university',
  'York University': 'york-university',
  'University of Victoria': 'university-of-victoria',
  'University of Windsor': 'university-of-windsor',
  'University of Guelph': 'university-of-guelph',
  'University of Manitoba': 'university-of-manitoba',
  'Toronto Metropolitan': 'toronto-metropolitan-university',
  'Univ of New Brunswick': 'university-of-new-brunswick',
};

const universities = fs.readFileSync(path.join(ROOT, 'data/universities.ts'), 'utf8');
const rows = [];
for (const [key, slug] of Object.entries(SLUGS)) {
  const e = INST[key];
  if (!e) throw new Error(`institution-english.json has no entry for ${key}`);
  if (!universities.includes(`slug: '${slug}'`)) {
    console.warn(`  skipped ${slug} — no such university in data/universities.ts`);
    continue;
  }
  const unresolved = e.resolved === false || e.doNotPublish === true;
  rows.push({
    slug,
    ielts: !unresolved && (e.ielts || []).length > 0,
    toefl: !unresolved && (e.toefl || []).length > 0,
    pte: !unresolved && (e.pte || []).length > 0,
    scope: 'institution-wide',
    sourceUrl: e.url || null,
    note: unresolved ? (e.unresolvedReason || 'Requirement is tiered; no institution-wide default stated.') : null,
  });
}
rows.sort((a, b) => a.slug.localeCompare(b.slug));

const lit = (v) => (v === null ? 'null' : typeof v === 'string' ? `'${v.replace(/'/g, "\\'")}'` : String(v));
const body = rows.map((r) => `  '${r.slug}': { ielts: ${r.ielts}, toefl: ${r.toefl}, pte: ${r.pte}, scope: ${lit(r.scope)}, sourceUrl: ${lit(r.sourceUrl)}, note: ${lit(r.note)} },`).join('\n');

const out = `// GENERATED by scripts/gen-english-published.js — do not edit by hand.
//
// Which English tests each university PUBLISHES a score for, from its own English-requirements
// page. \`false\` means: we looked, and the university did not state a score for that test — so the
// value carried on the course row is our house default and must never be printed as a requirement.
//
// Absent university = unknown, and lib/english-verification treats unknown as publishing all three
// (same deliberate default as lib/fee-verification: silence here must not blank out the ~42
// universities whose real per-course IELTS varies). Add universities here as they are checked.
//
// Canada rows come from data/wave-canada/institution-english.json (${rows.length} universities,
// generated ${new Date().toISOString().slice(0, 10)}).

export interface EnglishPublication {
  /** the university's own page states an IELTS score */
  ielts: boolean;
  toefl: boolean;
  pte: boolean;
  /** granularity of the published figure */
  scope: string;
  sourceUrl: string | null;
  /** why nothing is publishable, when all three are false */
  note: string | null;
}

export const ENGLISH_PUBLISHED: Record<string, EnglishPublication> = {
${body}
};
`;
fs.writeFileSync(path.join(ROOT, 'data/english-published.ts'), out);
console.log(`wrote data/english-published.ts — ${rows.length} universities`);
for (const r of rows) console.log(`  ${r.slug.padEnd(34)} ielts:${String(r.ielts).padEnd(5)} toefl:${String(r.toefl).padEnd(5)} pte:${String(r.pte).padEnd(5)}${r.note ? '  ' + r.note.slice(0, 60) : ''}`);
