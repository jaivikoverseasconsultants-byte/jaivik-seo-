// Writes data/jcu-brisbane-courses.ts from data/wave-australia/jcu-brisbane.json.
//
//   node scripts/crawl-jcu-brisbane.js && node scripts/gen-jcu-brisbane.js
//
// Every published figure is JCU's: fee and estimated total from JCU Brisbane's 2026 international
// tuition schedule; duration, Brisbane intakes, course and CRICOS codes from the course page's own
// data. KC (coursefinder.ai) only said which programmes to look for. Its "avg scholarship" and
// "initial deposit" figures are carried separately as kcEstimate — JCU publishes neither — and
// the course page labels them as partner-platform estimates, never as JCU's figures.
//
// English: JCU states an English band per course (Band 2 for these master's, Band 1 for the
// bachelor's) rather than a score on the page. The band-to-score table was not verified, so no
// IELTS/TOEFL/PTE score is published (englishScope marks the row) until it is.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'data/wave-australia/jcu-brisbane.json');
const OUT = path.join(ROOT, 'data/jcu-brisbane-courses.ts');
const RATE_TO_INR = { AUD: 54.6, USD: 83.5 }; // must match lib/currency.ts RATE_TO_INR

const crawl = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const MONTHS = { February: 'February', May: 'May', September: 'September', July: 'July', March: 'March' };

const rows = [];
for (const r of crawl.results) {
  if (r.dropped) continue;
  if (r.error || !r.jcu) throw new Error(`${r.kcName}: no JCU data (${r.error ?? 'missing'})`);
  if (r.major && !r.majorConfirmed) throw new Error(`${r.kcName}: major not confirmed on JCU's page`);
  const s = r.scheduleLine;
  const jcuName = r.jcu.name.replace(/\s*\[2-Year\]$/, '');
  const name = r.major ? `${jcuName} (${r.major})` : jcuName;
  const years = Number((r.jcu.durationFullTime.match(/([\d.]+)\s*years?/) || [])[1]) || 0;
  const intakes = (r.jcu.brisbaneCommencing || '').split(/,\s*/).filter((m) => MONTHS[m]);
  if (!intakes.length) throw new Error(`${r.kcName}: no Brisbane intake on JCU's page`);
  const isBachelor = /^Bachelor/.test(jcuName);
  const row = {
    id: `jcub-${rows.length + 1}`,
    name,
    // same prefix as the July 2026 file this replaces, so its URLs for the same programmes resolve again
    slug: `jcu-brisbane-${slugify(name)}`,
    url: r.url,
    level: isBachelor ? 'Bachelor' : 'Master',
    studyLevel: isBachelor ? 'Undergraduate' : 'Postgraduate',
    duration: `${years} year${years === 1 ? '' : 's'}`,
    durationYears: years,
    annualAUD: 0, annualUSD: 0, annualINR: 0, totalAUD: 0,
    ieltsMin: 0, toeflMin: 0, pteMin: 0,
    englishScope: `not published — JCU states English Band ${r.jcu.englishBand} for this course; the band's score table has not been verified here`,
    intakeMonths: intakes,
    campus: 'Brisbane',
    country: 'Australia', state: 'Queensland', city: 'Brisbane', countryCode: 'AU',
    courseCode: r.jcu.courseCode,
    cricos: r.jcu.cricos,
    ...(r.major ? { major: r.major } : {}),
    feeVerified: false,
    feeScope: 'not published',
    feeBasis: 'not published — no line for this programme in JCU Brisbane\'s 2026 international tuition schedule',
    feeSourceUrl: null,
  };
  if (s) {
    const pageFee = r.jcu.internationalFeeOnPage ? Number(r.jcu.internationalFeeOnPage.replace(/[^0-9.]/g, '')) : null;
    if (pageFee && pageFee !== s.annual2026) throw new Error(`${name}: schedule ${s.annual2026} but course page ${pageFee}`);
    Object.assign(row, {
      annualAUD: s.annual2026,
      annualINR: Math.round(s.annual2026 * RATE_TO_INR.AUD),
      annualUSD: Math.round((s.annual2026 * RATE_TO_INR.AUD) / RATE_TO_INR.USD),
      totalAUD: s.estimatedTotal,
      feeVerified: true,
      feeScope: 'programme',
      feeBasis: `annual international tuition for 2026, based on 8 subjects a year and including the Student Services and Amenities Fee, from JCU Brisbane's 2026 schedule (${s.subjects} subjects at A$${s.perSubject.toLocaleString('en-US', { minimumFractionDigits: 2 })} each; JCU's estimated total A$${s.estimatedTotal.toLocaleString('en-US')})${r.major ? `; the ${r.major} major is charged as the Master of Information Technology` : ''}`,
      feeSourceUrl: crawl._sources.fees,
    });
  }
  const sch = Number(r.kc['Avg Scholarship (AUD)']);
  const dep = Number(r.kc['Initial Deposit (AUD)']);
  if (sch > 0 || dep > 0) row.kcEstimate = { avgScholarshipAUD: sch || null, initialDepositAUD: dep || null };
  rows.push(row);
}

const slugs = new Set();
for (const r of rows) { if (slugs.has(r.slug)) throw new Error(`duplicate slug ${r.slug}`); slugs.add(r.slug); }

const out = `// JCU Brisbane — James Cook University's Brisbane campus (delivered with Russo Higher Education)
// Generated by scripts/gen-jcu-brisbane.js from data/wave-australia/jcu-brisbane.json — do not edit by hand.
// Discovery: KC (coursefinder.ai) listed which programmes exist; KC is not a source for any figure here.
// Fees: ${crawl._sources.fees}
//   (linked from ${crawl._sources.feesPage}) — 2026, 8 subjects/year, SSAF included.
// Course facts: each jcu.edu.au course page's embedded data (Brisbane intakes, duration, course + CRICOS codes).
// Verified: ${crawl._crawledOn} — every fee cross-checked against the course page's own international fee.
// KC was wrong for the Bachelor of Commerce (A$35,824 vs JCU's A$36,899) and gave Jan/May/Sep
// intakes where JCU states February/May/September.
// ${rows.length} courses

export interface JcuBrisbaneCourse {
  feeVerified?: boolean;
  id: string; name: string; slug: string; url: string;
  level: string; studyLevel: string; duration: string; durationYears: number;
  annualAUD: number; annualUSD: number; annualINR: number; totalAUD: number;
  ieltsMin: number; toeflMin: number; pteMin: number; englishScope?: string;
  intakeMonths: string[]; campus: string;
  country: string; state: string; city: string; countryCode: string;
  courseCode: string; cricos: string | null; major?: string;
  feeScope?: string; feeBasis?: string; feeSourceUrl?: string | null;
  /** KC partner-platform figures. JCU publishes neither; always shown labelled as estimates. */
  kcEstimate?: { avgScholarshipAUD: number | null; initialDepositAUD: number | null };
}

export const jcuBrisbaneCourses: JcuBrisbaneCourse[] = [
${rows.map((r) => `  ${JSON.stringify(r)}`).join(',\n')}
];

export function getJcuBrisbaneCourseBySlug(slug: string): JcuBrisbaneCourse | undefined {
  return jcuBrisbaneCourses.find(c => c.slug === slug);
}
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${rows.length} courses | fee verified ${rows.filter((r) => r.feeVerified).length} | with KC estimates ${rows.filter((r) => r.kcEstimate).length}`);
