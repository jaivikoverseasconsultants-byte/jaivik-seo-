const UNIVERSITY_SLUG = 'university-of-guelph';

function courseParams() {
  return (guelphCourses as unknown as any[]).map((c) => ({ slug: c.slug }));
}

async function courseMetadata(slug: string): Promise<Metadata> {
  const course = getGuelphCourseBySlug(slug) as any;
  if (!course) return {};
  const english = publishedEnglishTests(UNIVERSITY_SLUG, course as never).some((t) => t.label === 'IELTS Academic') ? ` IELTS ${course.ieltsMin}+.` : '';
  return buildMetadata({
    title: `${course.name} at University of Guelph`,
    description: `${course.name} at University of Guelph, Guelph${feeSentenceINR(course, course.annualINR)}${english} Apply with Jaivik Overseas — 13 years expertise, 99% visa success.`,
    path: `/universities/university-of-guelph/courses/${slug}`,
    keywords: [course.name, 'Guelph', 'University of Guelph', 'study in Canada', course.level],
  });
}

